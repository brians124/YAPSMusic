#!/usr/bin/env node
/*
 * YAPSMusic SEO builder
 * ---------------------
 * Generates one crawlable, indexable page per song so Google can show
 * YAPSMusic when someone searches "<song> <artist>".
 *
 * Usage (run from the site folder, re-run whenever songs change):
 *   SITE_URL=https://brians124.github.io/YAPSMusic node build-seo.js
 *   (or: node build-seo.js https://your-real-domain.com)
 *
 * Reads the song list (CAT) from music.html — the single source of truth —
 * and writes:
 *   song/<slug>.html   one page per song (title, meta, canonical, JSON-LD, player)
 *   songs/index.html   crawlable "All songs" hub linking to every song page
 *   sitemap.xml        every page, for Google Search Console
 *   robots.txt         allows crawling + points to the sitemap
 *   catalog.js         all songs for the hero player (hero-player.js) used on every page
 *   (signup-gate.js is a hand-written file, not generated: it asks visitors to create an account when they tap a song)
 *
 * The slug() function here MUST match slug() in music.html (it links to these pages).
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SITE = (process.argv[2] || process.env.SITE_URL || "https://brians124.github.io/YAPSMusic").replace(/\/+$/, "");
const APP_URL = "https://brians124.github.io/YAPSMUSIC.APP/";
const TODAY = new Date().toISOString().slice(0, 10);

/* ---------- helpers ---------- */
const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const asset = p => (/^https?:/.test(p) ? p : APP_URL + encodeURI(p));
const primary = a => a.split(/ ft\.| feat\.| & |,/i)[0].trim();
const part = s => String(s).normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase()
  .replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48).replace(/-+$/g, "");
const slug = t => [part(t.title), part(t.artist), t.id].filter(Boolean).join("-");
const an = w => (/^[aeiou]/i.test(w) ? "an " : "a ") + w;
const iso = d => { const [m, s] = String(d).split(":").map(Number); return `PT${m || 0}M${s || 0}S`; };

/* ---------- load catalogue ---------- */
const music = fs.readFileSync(path.join(ROOT, "music.html"), "utf8");
const m = music.match(/const CAT=(\[\[[\s\S]*?\]\]);/);
if (!m) throw new Error("Could not find `const CAT=[[...]]` in music.html");
const CAT = new Function("return " + m[1])();
const ART = (() => {
  try {
    const a = fs.readFileSync(path.join(ROOT, "artist.html"), "utf8").match(/const ART=(\[\[[\s\S]*?\]\]);/);
    return a ? new Function("return " + a[1])() : [];
  } catch { return []; }
})();
/* catalog.js: the same song list, for the hero player that every page loads (hero-player.js) */
fs.writeFileSync(path.join(ROOT, "catalog.js"),
  "/* GENERATED by build-seo.js from the CAT list in music.html. Do not edit by hand; re-run build-seo.js. */\n" +
  "window.YAPS_CAT=" + JSON.stringify(CAT.map(c => c.slice(0, 7))) + ";\n");

const artistKnown = new Set(ART.map(a => a[0].toLowerCase()));

const T = CAT.map(c => ({ id: c[0], title: c[1], artist: c[2], img: c[3], audio: c[4], dur: c[5], genre: c[6], fl: c[7] || "", yt: (c[8] || "").trim() }))
  .map(t => ({ ...t, pa: primary(t.artist), slug: slug(t) }));

const seen = new Set();
for (const t of T) { if (seen.has(t.slug)) throw new Error("Duplicate slug: " + t.slug); seen.add(t.slug); }

/* ---------- shared page shell ---------- */
const CSS = `:root{--ink:#0c0d0f;--txt:#f4f5f7;--mute:#b9bdc4;--sky:#d2d5da;--line:rgba(214,217,222,.2);--glass:rgba(214,217,222,.085);--btn:linear-gradient(100deg,#868b93 0%,#5f636a 50%,#464a50 100%);color-scheme:dark}
*,*::before,*::after{box-sizing:border-box;margin:0}
html{background:var(--ink);overflow-x:clip}
body{font:400 16px/1.55 Archivo,system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;color:var(--txt);background:radial-gradient(circle at 8% 0%,rgba(226,228,232,.16),transparent 42%),radial-gradient(circle at 100% 12%,rgba(140,145,153,.22),transparent 46%),linear-gradient(180deg,#121316,#0c0d0f 60%,#16181b);background-attachment:fixed;min-height:100vh}
a{color:inherit;text-decoration:none}
.wrap{width:100%;padding-inline:clamp(14px,2vw,40px)}main.wrap{padding-inline:clamp(14px,2vw,40px)}.wrap .wrap{padding-inline:0}
header{position:sticky;top:0;z-index:5;background:rgba(14,15,17,.7);backdrop-filter:blur(20px);-webkit-backdrop-filter:blur(20px);border-bottom:1px solid var(--line)}
.bar{display:flex;align-items:center;gap:16px;min-height:64px;flex-wrap:wrap;padding:8px clamp(14px,2vw,40px)}
.logo{font-weight:800;font-size:20px;letter-spacing:-.03em}.logo i{font-style:normal;color:var(--sky)}
nav{margin-left:auto;display:flex;gap:4px;flex-wrap:wrap}
nav a{padding:8px 12px;border-radius:999px;font-size:14px;color:var(--mute)}nav a:hover{color:#fff;background:var(--glass)}
.crumbs{padding:22px 0 0;font-size:13px;color:var(--mute)}.crumbs a:hover{color:#fff;text-decoration:underline}
.glass{background:transparent;border:0;border-radius:12px}
.btn{display:inline-flex;align-items:center;gap:8px;padding:12px 22px;border-radius:999px;border:1px solid var(--line);background:rgba(214,217,222,.1);font-weight:600;min-height:44px}
.btn.pri{background:var(--btn);border-color:rgba(255,255,255,.18);box-shadow:0 8px 26px rgba(0,0,0,.4)}
.btn:hover{border-color:rgba(226,228,232,.5)}
.hero{display:grid;grid-template-columns:clamp(220px,22vw,360px) 1fr;gap:clamp(24px,4vw,64px);align-items:center;padding:28px 0 12px}
.art{aspect-ratio:1;border-radius:18px;overflow:hidden;background:linear-gradient(135deg,#7a7f87,#25282c);display:grid;place-items:center;font-size:56px;font-weight:800;position:relative}
.art img{position:absolute;inset:0;width:100%;height:100%;object-fit:cover}
.kind{font-size:13px;letter-spacing:.12em;text-transform:uppercase;color:var(--mute)}
h1{font-size:clamp(30px,5vw,52px);line-height:1.08;letter-spacing:-.02em;margin:6px 0 10px;overflow-wrap:anywhere}
.by{font-size:18px;color:var(--mute)}.by a{color:var(--txt);font-weight:600}.by a:hover{text-decoration:underline}
.facts{display:flex;gap:10px;flex-wrap:wrap;margin:16px 0}
.facts span{padding:5px 14px;border-radius:999px;background:var(--glass);border:1px solid var(--line);font-size:14px}
audio{width:100%;max-width:560px;margin:6px 0 16px;display:block}
.acts{display:flex;gap:12px;flex-wrap:wrap}
section{padding:28px 0}
h2{font-size:clamp(20px,3vw,26px);font-weight:800;letter-spacing:-.02em;margin-bottom:16px}
.about p{color:var(--mute);max-width:70ch}
.list{display:grid;grid-template-columns:repeat(auto-fill,minmax(280px,1fr));gap:6px 18px}
.row{display:flex;align-items:center;gap:12px;padding:10px 14px;min-width:0}
.row:hover{background:rgba(255,255,255,.07)}
.row .c{width:52px;height:52px;border-radius:10px;overflow:hidden;flex:none;background:linear-gradient(135deg,#7a7f87,#25282c);position:relative}
.row .c img{position:absolute;inset:0;width:100%;height:100%;object-fit:cover}
.row b{display:block;font-size:15px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.row small{display:block;color:var(--mute);font-size:13px;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.row div{min-width:0}
.az h2{margin-top:10px;color:var(--sky)}
footer{border-top:1px solid var(--line);padding:28px 0;margin-top:20px;color:var(--mute);font-size:14px}
footer .wrap{display:flex;gap:16px;justify-content:space-between;flex-wrap:wrap}
footer a:hover{color:#fff}
@media(max-width:720px){.hero{grid-template-columns:1fr;gap:20px}.art{max-width:240px}nav{margin-left:0}}`;

const FONT = `<link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link href="https://fonts.googleapis.com/css2?family=Archivo:wght@400;600;800;900&display=swap" rel="stylesheet">`;

const shell = ({ title, desc, canonical, ogImage, ogType, jsonld, body, depth, hero }) => {
  const up = "../".repeat(depth);
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#0c0d0f">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<meta name="robots" content="index, follow, max-image-preview:large">
<link rel="canonical" href="${esc(canonical)}">
<meta property="og:site_name" content="YAPSMusic">
<meta property="og:type" content="${ogType}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${esc(canonical)}">
<meta property="og:image" content="${esc(ogImage)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(desc)}">
<meta name="twitter:image" content="${esc(ogImage)}">
${FONT}
<link rel="icon" href="https://brians124.github.io/YAPSMUSIC.APP/favicon.ico?v=2">
<link rel="icon" type="image/png" sizes="32x32" href="https://brians124.github.io/YAPSMUSIC.APP/icons/favicon-32.png?v=2">
<link rel="apple-touch-icon" href="https://brians124.github.io/YAPSMUSIC.APP/icons/apple-touch-icon.png?v=2">
<style>${CSS}</style>
<link rel="stylesheet" href="${up}logo.css">
<script type="application/ld+json">${JSON.stringify(jsonld).replace(/</g, "\\u003c")}</script>
</head>
<body${hero ? ` data-hero="${hero}"` : ""}>
<header><div class="wrap bar">
<a class="logo" href="${up}index.html" aria-label="YAPS Music home"><span class="yl-bicon" aria-hidden="true"></span><span class="yl-bword">YAPS</span><span class="yl-bmusic">MUSIC</span></a>
<nav aria-label="Main"><a href="${up}index.html">Home</a><a href="${up}music.html">Music</a><a href="${up}songs/index.html">All songs</a><a href="${up}artists.html">Artists</a><a href="${up}charts.html">Charts</a><a href="${up}videos.html">Videos</a><a href="${up}search.html">Search</a></nav>
</div></header>
${body}
<footer><div class="wrap"><span>© ${new Date().getFullYear()} YAPSMusic · Music to the World, from Uganda</span><span><a href="${up}about.html">About</a> · <a href="${up}contact.html">Contact</a> · <a href="${up}join.html">For artists</a></span></div></footer>
<script src="${up}signup-gate.js" defer></script>
<script src="${up}hero-player.js" defer></script>
</body>
</html>
`;
};

const initials = s => s.split(/\s+/).map(w => w[0]).filter(Boolean).slice(0, 2).join("").toUpperCase();
const cover = (t, cls) => `<div class="${cls}">${cls === "art" ? esc(initials(t.title)) : ""}<img src="${esc(asset(t.img))}" alt="${cls === "art" ? esc(`${t.title} by ${t.artist} cover art`) : ""}" loading="${cls === "art" ? "eager" : "lazy"}" onerror="this.remove()"></div>`;
const row = (t, up) => `<a class="glass row" href="${up}${t.slug}.html">${cover(t, "c")}<div><b>${esc(t.title)}</b><small>${esc(t.artist)}</small></div></a>`;

/* ---------- song pages ---------- */
fs.rmSync(path.join(ROOT, "song"), { recursive: true, force: true });
fs.mkdirSync(path.join(ROOT, "song"), { recursive: true });

for (const t of T) {
  const url = `${SITE}/song/${t.slug}.html`;
  const title = `${t.title} – ${t.artist} | YAPSMusic`;
  const desc = `Listen to ${t.title} by ${t.artist} on YAPSMusic. ${an(t.genre).replace(/^a/, "A")} song from Uganda and East Africa, ${t.dur} long. Play it here or open it in the YAPSMusic app.`;
  const same = T.filter(x => x.id !== t.id && x.pa.toLowerCase() === t.pa.toLowerCase());
  const likeG = T.filter(x => x.id !== t.id && x.genre === t.genre && !same.includes(x));
  const related = same.concat(likeG).slice(0, 6);
  const artistHref = artistKnown.has(t.pa.toLowerCase()) ? `../artist.html?artist=${encodeURIComponent(t.pa)}` : null;
  const by = artistHref
    ? `<a href="${artistHref}">${esc(t.pa)}</a>${esc(t.artist.slice(t.pa.length))}`
    : esc(t.artist);

  const jsonld = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "MusicRecording",
        "@id": url + "#song",
        name: t.title,
        url,
        byArtist: { "@type": "MusicGroup", name: t.pa },
        genre: t.genre,
        duration: iso(t.dur),
        image: asset(t.img),
        audio: { "@type": "AudioObject", contentUrl: asset(t.audio), encodingFormat: "audio/mpeg", duration: iso(t.dur) },
        inLanguage: "en",
        isPartOf: { "@type": "WebSite", name: "YAPSMusic", url: SITE + "/" },
        ...(t.yt ? { sameAs: `https://www.youtube.com/watch?v=${t.yt}` } : {}),
      },
      {
        "@type": "BreadcrumbList",
        itemListElement: [
          { "@type": "ListItem", position: 1, name: "YAPSMusic", item: SITE + "/" },
          { "@type": "ListItem", position: 2, name: "All songs", item: SITE + "/songs/index.html" },
          { "@type": "ListItem", position: 3, name: t.title, item: url },
        ],
      },
    ],
  };

  const body = `<main class="wrap">
<div class="crumbs" aria-label="Breadcrumb"><a href="../index.html">Home</a> › <a href="../songs/index.html">All songs</a> › ${esc(t.title)}</div>
<div class="hero">
${cover(t, "art")}
<div>
<span class="kind">Song</span>
<h1>${esc(t.title)}</h1>
<p class="by">by ${by}</p>
<div class="facts"><span>${esc(t.genre)}</span><span>${esc(t.dur)}</span><span>Uganda &amp; East Africa</span></div>
<audio controls preload="none" src="${esc(asset(t.audio))}">Your browser does not support audio playback.</audio>
<div class="acts"><a class="btn pri" href="${APP_URL}?track=${t.id}">Listen in YAPSMusic App</a>${t.yt ? `<a class="btn" href="https://www.youtube.com/watch?v=${esc(t.yt)}" target="_blank" rel="noopener">Watch the video</a>` : ""}</div>
</div>
</div>
<section class="about"><h2>About ${esc(t.title)}</h2>
<p>${esc(t.title)} is ${an(esc(t.genre))} song by ${esc(t.artist)}, available on YAPSMusic${t.yt ? ", with a music video on YouTube" : ""}. YAPSMusic brings you music from Uganda and East Africa — discover more ${esc(t.genre)} songs${artistHref ? ` and the full <a href="${artistHref}" style="text-decoration:underline">${esc(t.pa)} profile</a>` : ""}.</p></section>
${related.length ? `<section><h2>${same.length ? `More from ${esc(t.pa)}` : `More ${esc(t.genre)} songs`}</h2><div class="list">${related.map(r => row(r, "")).join("")}</div></section>` : ""}
</main>`;

  fs.writeFileSync(path.join(ROOT, "song", t.slug + ".html"), shell({ title, desc, canonical: url, ogImage: asset(t.img), ogType: "music.song", jsonld, body, depth: 1, hero: "song" }));
}

/* ---------- hub: songs/index.html ---------- */
fs.mkdirSync(path.join(ROOT, "songs"), { recursive: true });
const sorted = [...T].sort((a, b) => a.title.localeCompare(b.title, "en", { sensitivity: "base" }));
const groups = {};
for (const t of sorted) { const k = /[a-z]/i.test(t.title.normalize("NFD")[0]) ? t.title.normalize("NFD")[0].toUpperCase() : "#"; (groups[k] = groups[k] || []).push(t); }
const hubUrl = `${SITE}/songs/index.html`;
const hubBody = `<main class="wrap">
<div class="crumbs" aria-label="Breadcrumb"><a href="../index.html">Home</a> › All songs</div>
<div style="padding:26px 0 6px"><span class="kind">Library</span><h1>All songs on YAPSMusic</h1><p class="by">${T.length} songs from Uganda and East Africa — pick any title to listen.</p></div>
<div class="az">${Object.keys(groups).sort().map(k => `<section><h2>${k}</h2><div class="list">${groups[k].map(t => row(t, "../song/")).join("")}</div></section>`).join("")}</div>
</main>`;
fs.writeFileSync(path.join(ROOT, "songs", "index.html"), shell({
  title: "All Songs from Uganda & East Africa | YAPSMusic",
  desc: `Browse all ${T.length} songs on YAPSMusic — Afrobeats, Luganda Pop, Gospel and more from Uganda and East Africa.`,
  canonical: hubUrl, ogImage: APP_URL + "images/yaps-music-cover.jpg", ogType: "website",
  jsonld: { "@context": "https://schema.org", "@type": "CollectionPage", name: "All songs on YAPSMusic", url: hubUrl, isPartOf: { "@type": "WebSite", name: "YAPSMusic", url: SITE + "/" },
    mainEntity: { "@type": "ItemList", numberOfItems: T.length, itemListElement: sorted.map((t, i) => ({ "@type": "ListItem", position: i + 1, url: `${SITE}/song/${t.slug}.html`, name: `${t.title} – ${t.artist}` })) } },
  body: hubBody, depth: 1, hero: "hub",
}));

/* ---------- sitemap + robots ---------- */
const pages = ["index.html", "music.html", "songs/index.html", "artists.html", "charts.html", "videos.html", "events.html", "podcasts.html", "news.html", "about.html", "contact.html", "join.html", "download.html"]
  .filter(p => fs.existsSync(path.join(ROOT, p)));
const urls = [
  ...pages.map(p => ({ loc: `${SITE}/${p === "index.html" ? "" : p}`, pr: p === "index.html" ? "1.0" : p === "songs/index.html" || p === "music.html" ? "0.9" : "0.6" })),
  ...T.map(t => ({ loc: `${SITE}/song/${t.slug}.html`, pr: "0.8" })),
];
fs.writeFileSync(path.join(ROOT, "sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(u => `  <url><loc>${esc(u.loc)}</loc><lastmod>${TODAY}</lastmod><priority>${u.pr}</priority></url>`).join("\n")}
</urlset>
`);
fs.writeFileSync(path.join(ROOT, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);

console.log(`Built ${T.length} song pages, songs/index.html, sitemap.xml (${urls.length} URLs), robots.txt`);
console.log(`SITE_URL = ${SITE}${false ? "   <-- placeholder! re-run with your real domain" : ""}`);
